// HTML is allowed only for these trusted, static translation values.
const HTML_TRANSLATION_KEYS = new Set([
  "aboutTitle",
  "skillsTitle",
  "projectsTitle",
  "contactTitle"
]);

const LANGUAGE_STORAGE_KEY = "portfolio-language";

const languageButton = document.querySelector(".language-toggle");
const menuButton = document.querySelector(".menu-toggle");
const navigation = document.querySelector(".nav");

// Apply translations to all elements.
function updatePageTranslations(dictionary) {
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;

    if (!Object.hasOwn(dictionary, key)) {
      return;
    }

    const translation = dictionary[key];

    if (HTML_TRANSLATION_KEYS.has(key)) {
      element.innerHTML = translation;
    } else {
      element.textContent = translation;
    }
  });
}

// Update language button and document direction.
function updateLanguageInterface(language) {
  const isEnglish = language === "en";

  document.documentElement.lang = language;
  document.documentElement.dir = isEnglish ? "ltr" : "rtl";

  if (languageButton) {
    languageButton.textContent = isEnglish ? "فا" : "EN";

    languageButton.setAttribute(
      "aria-label",
      isEnglish
        ? "تغییر زبان به فارسی"
        : "Switch language to English"
    );
  }

  updateMenuAccessibility(language);
}

// Update mobile menu accessibility labels.
function updateMenuAccessibility(language) {
  if (!menuButton) {
    return;
  }

  const dictionary = translations[language];
  const isOpen = menuButton.getAttribute("aria-expanded") === "true";

  menuButton.setAttribute(
    "aria-label",
    isOpen ? dictionary.menuClose : dictionary.menuOpen
  );
}

// Save selected language.
function saveLanguage(language) {
  try {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
  } catch {
    // Continue without saving if storage is unavailable.
  }
}

// Change website language.
function setLanguage(language) {
  const selectedLanguage = Object.hasOwn(translations, language)
    ? language
    : "en";

  const dictionary = translations[selectedLanguage];

  updatePageTranslations(dictionary);
  updateLanguageInterface(selectedLanguage);
  saveLanguage(selectedLanguage);
}

// Get previously selected language.
function getInitialLanguage() {
  try {
    const savedLanguage = localStorage.getItem(LANGUAGE_STORAGE_KEY);

    if (Object.hasOwn(translations, savedLanguage)) {
      return savedLanguage;
    }
  } catch {
    // Use English if storage is unavailable.
  }

  return "en";
}

// Toggle website language.
function handleLanguageToggle() {
  const currentLanguage = document.documentElement.lang;
  const nextLanguage = currentLanguage === "en" ? "fa" : "en";

  setLanguage(nextLanguage);
}

// Toggle mobile navigation.
function handleMenuToggle() {
  if (!navigation || !menuButton) {
    return;
  }

  const isOpen = navigation.classList.toggle("is-open");

  menuButton.setAttribute("aria-expanded", String(isOpen));

  updateMenuAccessibility(document.documentElement.lang);
}

// Close mobile navigation after selecting a link.
function handleNavigationClick() {
  if (!navigation || !menuButton) {
    return;
  }

  navigation.classList.remove("is-open");
  menuButton.setAttribute("aria-expanded", "false");

  updateMenuAccessibility(document.documentElement.lang);
}

// Initialize event listeners.
function initializeEventListeners() {
  languageButton?.addEventListener("click", handleLanguageToggle);
  menuButton?.addEventListener("click", handleMenuToggle);

  navigation?.querySelectorAll("a").forEach((link) => {
    link.addEventListener("click", handleNavigationClick);
  });
}

// Initialize website.
function initializeWebsite() {
  setLanguage(getInitialLanguage());
  initializeEventListeners();
}

initializeWebsite();
